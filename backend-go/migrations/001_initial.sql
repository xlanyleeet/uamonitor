CREATE TABLE servers (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    ip text NOT NULL CHECK (length(ip) BETWEEN 1 AND 253),
    port integer NOT NULL DEFAULT 25565 CHECK (port BETWEEN 1 AND 65535),
    icon text,
    change_icon boolean NOT NULL DEFAULT true,
    telegram text,
    discord text,
    youtube text,
    link text,
    description text,
    UNIQUE (ip, port)
);

CREATE TABLE statuses (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    server_id integer NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
    is_online boolean NOT NULL,
    online_count integer CHECK (online_count >= 0),
    max_online integer CHECK (max_online >= 0),
    version text,
    date timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX statuses_server_date_idx ON statuses (server_id, date DESC, id DESC);
CREATE INDEX statuses_date_idx ON statuses (date);
